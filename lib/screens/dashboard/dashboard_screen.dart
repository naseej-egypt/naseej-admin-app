  Widget _buildChartCard({
    required BuildContext context,
    required String title,
    required RxList<String> labels,
    required RxList<double> values,
    required Color color,
    double width = 400,
  }) {
    return Obx(() {
      if (labels.isEmpty || values.isEmpty) {
        return SizedBox(
          width: width,
          child: Card(
            child: Padding(
              padding: const EdgeInsets.all(16),
              child: Center(child: Text('No data available for $title')),
            ),
          ),
        );
      }

      return SizedBox(
        width: width,
        child: Card(
          child: Padding(
            padding: const EdgeInsets.all(16),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(title, style: Theme.of(context).textTheme.titleMedium),
                const SizedBox(height: 16),
                Expanded(
                  child: _buildSimpleBarChart(labels.value, values.value, context, color),
                ),
              ],
            ),
          ),
        ),
      );
    });
  }

  Widget _buildSimpleBarChart(List<String> labels, List<double> values, BuildContext context, Color color) {
    if (labels.isEmpty || values.isEmpty) return const Center(child: Text('No data'));
    final maxValue = values.reduce((a, b) => a > b ? a : b);
    if (maxValue == 0) return const Center(child: Text('No sales data'));

    return Row(
      mainAxisAlignment: MainAxisAlignment.spaceEvenly,
      crossAxisAlignment: CrossAxisAlignment.end,
      children: List.generate(labels.length, (index) {
        final height = (values[index] / maxValue) * 150;
        return Expanded(
          child: Padding(
            padding: const EdgeInsets.symmetric(horizontal: 2),
            child: Column(
              mainAxisAlignment: MainAxisAlignment.end,
              mainAxisSize: MainAxisSize.min,
              children: [
                Flexible(
                  child: Text(
                    values[index] >= 1000 ?
                    '\$${(values[index] / 1000).toStringAsFixed(1)}k' :
                    '\$${values[index].toStringAsFixed(0)}',
                    style: const TextStyle(fontSize: 9),
                    maxLines: 1,
                    overflow: TextOverflow.ellipsis,
                  ),
                ),
                const SizedBox(height: 2),
                Container(
                  height: height,
                  decoration: BoxDecoration(
                    color: color,
                    borderRadius: BorderRadius.circular(3),
                  ),
                ),
                const SizedBox(height: 4),
                Flexible(
                  child: Text(
                    labels[index],
                    style: const TextStyle(fontSize: 9),
                    maxLines: 1,
                    overflow: TextOverflow.ellipsis,
                  ),
                ),
              ],
            ),
          ),
        );
      }),
    );
  }

